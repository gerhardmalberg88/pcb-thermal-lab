def amgx_configuration():
    # Based on NVIDIA AMGX's FGMRES_CLASSICAL_AGGRESSIVE_HMIS configuration.
    # FGMRES tolerates the nonsymmetric multigrid preconditioner; PCG does not.
    return {'config_version':2,'solver':{
        'scope':'main','solver':'FGMRES','print_solve_stats':1,'obtain_timings':1,
        'max_iters':5000,'monitor_residual':1,'gmres_n_restart':100,
        'convergence':'RELATIVE_INI','tolerance':1e-8,'norm':'L2',
        'preconditioner':{'scope':'amg_solver','solver':'AMG','algorithm':'CLASSICAL',
            'selector':'HMIS','interpolator':'D2','aggressive_levels':1,
            'interp_max_elements':4,'smoother':{'scope':'jacobi','solver':'JACOBI_L1','relaxation_factor':1},
            'presweeps':2,'postsweeps':2,'coarsest_sweeps':2,'coarse_solver':'NOSOLVER',
            'max_iters':1,'max_row_sum':.9,'strength_threshold':.25,'min_coarse_rows':2,
            'max_levels':50,'cycle':'V'}}}

def surface_area(mesh):
    import numpy as np
    nodes=mesh['nodes'];total=0.0
    for tri in (mesh['triangles'],mesh['quads'][mesh['quad_ids']==101][:,[0,1,2]],mesh['quads'][mesh['quad_ids']==101][:,[0,2,3]]):
        p=nodes[tri];total+=float(np.linalg.norm(np.cross(p[:,1]-p[:,0],p[:,2]-p[:,0]),axis=1).sum()/2)
    return total

def generate(case,power,meta,out,backend='cpu',ranks=1,mesh_directory='mesh',surface_area_m2=None):
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    transient=case['analysis']=='transient';ambient=case['cooling']['ambient_c']+273.15
    cached=transient and case.get('numerics',{}).get('cache_bulk',True)
    fast=transient and case.get('numerics',{}).get('fast_audit',True)
    bodies={int(k):v for k,v in meta['bodies'].items()};materials=meta['materials'];mids={name:i+1 for i,name in enumerate(materials)}
    lines=['! Generated by PCB Thermal Lab. Units: m, kg, s, W, K.',
           '! This SIF is authoritative. GUI Sif/Generate replaces manual settings.',
           'Check Keywords Warn','Header',f'  Mesh DB "." "{mesh_directory}"','End','',
           'Simulation','  Max Output Level = 6','  Coordinate System = Cartesian 3D',
           '  Simulation Type = '+('Transient' if transient else 'Steady State'),
           '  Steady State Max Iterations = 1','  Output File = "case.result"','  Output File Final Only = Logical True']
    if transient:
        t=case['transient'];dt=t['step_s'];steps=round((t['on_s']+t['off_s'])/dt)
        lines+=['  Timestepping Method = BDF','  BDF Order = 1',f'  Timestep Intervals(1) = {steps}',f'  Timestep Sizes(1) = {dt:.12g}','  Output Intervals(1) = 1']
    lines+=['End','Constants','End','Initial Condition 1',f'  Temperature = {ambient:.12g}','End',
            'Equation 1','  Active Solvers(5) = 1 2 3 4 5','End','Solver 1','  Equation = Heat Equation',
            '  Procedure = "HeatSolve" "HeatSolver"','  Variable = Temperature','  Variable Dofs = 1',
            '  Linear System Symmetric = Logical True','  Linear System Abort Not Converged = Logical True',
            f'  Linear System Convergence Tolerance = {case.get("numerics",{}).get("linear_tolerance",1e-10)}',
            f'  Linear System Max Iterations = {case.get("numerics",{}).get("max_iterations",5000)}',
            '  Linear System Residual Output = 100', '  Nonlinear System Max Iterations = 1',
            '  Steady State Convergence Tolerance = 1.0e-9','  Stabilize = Logical False']
    if backend=='cuda':lines+=['  Linear System Solver = amgx','  AMGX Config = String "amgx.json"']
    elif case.get('execution',{}).get('cpu_solver')=='cholmod':
        if ranks!=1:raise WorkflowError('CHOLMOD requires one CPU rank; set --mpi-ranks 1')
        lines+=['  Linear System Solver = Direct','  Linear System Direct Method = Cholmod']
    else:lines+=['  Linear System Solver = Iterative','  Linear System Iterative Method = CG','  Linear System Use Hypre = Logical True','  Linear System Preconditioning = BoomerAMG','  BoomerAMG Strong Threshold = 0.7','  BoomerAMG Coarsen Type = 10','  BoomerAMG Interpolation Type = 6','  BoomerAMG Relax Type = 6']
    lines+=['End']
    if cached:
        lines=[line.replace('Procedure = "HeatSolve" "HeatSolver"','Procedure = "ScheduledHeat" "ScheduledHeat"') for line in lines]
        lines[-1:-1]=['  Constant Bulk System = Logical True','  Linear System Refactorize = Logical False',
                       f'  Thermal On Seconds = Real {case["transient"]["on_s"]}',
                       f'  Thermal Phase Seconds = Real {power.get("phase_s",5)}']
    if fast:lines=[x.replace('Active Solvers(5) = 1 2 3 4 5','Active Solvers(6) = 1 2 3 4 5 6') for x in lines]
    cadence=round(case['transient']['field_interval_s']/case['transient']['step_s']) if transient else 1
    lines+=['Solver 2','  Exec Solver = After Timestep',f'  Exec Interval = {cadence}','  Exec Intervals Offset(1) = -1',
            '  Equation = ComputeFlux','  Procedure = "FluxSolver" "FluxSolver"','  Target Variable = Temperature',
            '  Flux Coefficient = "Heat Conductivity"','  Calculate Flux = Logical True',
            '  Linear System Solver = Iterative','  Linear System Iterative Method = CG',
            '  Linear System Preconditioning = Diagonal','  Linear System Convergence Tolerance = 1.0e-9',
            '  Linear System Max Iterations = 1000','End',
            'Solver 3','  Exec Solver = '+('After Simulation' if fast else 'After Timestep'),'  Equation = ScalarAudit',
            '  Procedure = "ThermalScalars" "SaveScalars"','  Filename = "scalars.dat"','  Parallel Reduce = Logical True']
    columns=[]
    def scalar(name,variable,operator,mask=None,coefficient=None):
        i=len(columns)+1;columns.append(name)
        lines.extend([f'  Variable {i} = "{variable}"',f'  Operator {i} = "{operator}"',f'  Mask Name {i} = "{mask or "audit_all"}"'])
        if coefficient:lines.append(f'  Coefficient {i} = "{coefficient}"')
    scalar('time_s','Time','value')
    scalar('temperature_min_k','Temperature','min');scalar('temperature_max_k','Temperature','max')
    scalar('energy_absolute_j','Temperature','int',coefficient='Volumetric Heat Capacity')
    scalar('exposed_temperature_integral_k_m2','Temperature','boundary int','audit_exposed')
    scalar('exposed_area_m2','Temperature','area','audit_exposed')
    for ref in power['resistors']:
        scalar(ref+'_min_k','Temperature','body min','audit_'+ref)
        scalar(ref+'_max_k','Temperature','body max','audit_'+ref)
        scalar(ref+'_mean_k','Temperature','body int mean','audit_'+ref)
    scalar('board_min_k','Temperature','body min','audit_board')
    scalar('board_max_k','Temperature','body max','audit_board')
    lines+=['End','Solver 4','  Exec Solver = After Timestep',f'  Exec Interval = {cadence}','  Exec Intervals Offset(1) = -1',
            '  Equation = OutputFields','  Procedure = "ResultOutputSolve" "ResultOutputSolver"',
            '  Output File Name = "temperature"','  Vtu Format = Logical True','  Binary Output = Logical True',
            '  Vtu Time Collection = Logical True',
            '  Single Precision = Logical False','  Save Geometry Ids = Logical True','End',
            'Solver 5','  Exec Solver = After Simulation','  Equation = SectionSamples','  Procedure = "SaveData" "SaveLine"',
            '  Filename = "section.dat"','  Variable 1 = Temperature']
    low,high=meta['bounds_m'];y=(low[1]+high[1])/2;zz=(min(high[2],0)+low[2])/2
    outputs=case.get('outputs',{})
    points=outputs.get('line_mm')
    coords=[v*1e-3 for pt in points for v in pt] if points else [low[0]+1e-6,y,zz,high[0]-1e-6,y,zz]
    lines += ['  Polyline Coordinates(2,3) = '+' '.join(str(v) for v in coords),
              f'  Polyline Divisions(1) = {outputs.get("line_divisions",200)}','End']
    if fast:
        lines += ['Solver 6','  Exec Solver = After Timestep','  Equation = FastScalarAudit',
                  '  Procedure = "FastAudit" "FastAudit"','  Filename = "fast-scalars.dat"',
                  f'  Thermal Heater Count = Integer {len(power["resistors"])}','End']
    heat_ids={};total_capacity=0.
    for ident,b in bodies.items():
        mat=materials[b['material']];total_capacity+=mat['density']*mat['heat_capacity']*b['volume_m3']
        lines += [f'Body {ident}',f'  Target Bodies(1) = {ident}',f'  Name = "{b["name"]}"',
                  '  Equation = 1',f'  Material = {mids[b["material"]]}','  Initial Condition = 1','  audit_all = Logical True']
        if b['name'].startswith(('board_','hybrid_')):lines.append('  audit_board = Logical True')
        if b.get('ref'):
            ref=b['ref'];heat_ids[ident]=b
            lines += [f'  Body Force = {ident}',f'  audit_{ref} = Logical True']
            lines += [f'  Thermal Heater Index = Integer {list(power["resistors"]).index(ref)+1}']
